-- eval/release/rockspec.lua — the rockspec, generated (development only; never shipped).
--
--   luajit eval/release/rockspec.lua VERSION        write luamemo-VERSION-1.rockspec
--   luajit eval/release/rockspec.lua VERSION --print  print it instead
--   luajit eval/release/rockspec.lua VERSION --check  exit 1 when that file differs from
--                                                     what this script writes (or is missing)
--   luajit eval/release/rockspec.lua --modules        print the module list (name<TAB>path)
--
-- Every luamemo/**/*.lua is a module (luamemo/x/init.lua → luamemo.x): a module can't be
-- left out of the rock by hand any more (0.4.1 missed 16). Run from the repository root.
-- The release workflow runs --check for the version it releases; eval/tests/test_rockspec.lua
-- checks the newest committed rockspec the same way.

local M = {}

--- { {name, path}, … } — every luamemo module, sorted by name.
function M.modules(root)
    root = root or "."
    local p = assert(io.popen(("cd %q && find luamemo -name '*.lua' -type f | LC_ALL=C sort"):format(root)))
    local out = {}
    for path in p:lines() do
        local name = path:gsub("%.lua$", ""):gsub("/init$", ""):gsub("/", ".")
        out[#out + 1] = { name = name, path = path }
    end
    p:close()
    table.sort(out, function(a, b) return a.name < b.name end)
    return out
end

