--- The rockspec's text for a version.
function M.render(version, root)
    local lines, width = {}, 0
    local mods = M.modules(root)
    for _, m in ipairs(mods) do width = math.max(width, #m.name) end
    for _, m in ipairs(mods) do
        lines[#lines + 1] = ('        [%q]%s = %q,'):format(m.name, (" "):rep(width - #m.name), m.path)
    end
    return (TEMPLATE:gsub("{{VERSION}}", version):gsub("{{MODULES}}", function() return table.concat(lines, "\n") end))
end

function M.file(version) return ("luamemo-%s-1.rockspec"):format(version) end

local function main(argv)
    if argv[1] == "--modules" then
        for _, m in ipairs(M.modules()) do io.write(m.name, "\t", m.path, "\n") end
        return 0
    end
    local version = argv[1]
    if not version or not version:match("^%d+%.%d+%.%d+$") then
        io.stderr:write("usage: luajit eval/release/rockspec.lua VERSION [--check] | --modules\n")
        return 2
    end
    local text, path = M.render(version), M.file(version)
    if argv[2] == "--print" then io.write(text); return 0 end
    if argv[2] == "--check" then
        local f = io.open(path, "r")
        local have = f and f:read("*a"); if f then f:close() end
        if have == text then io.write(path, " is up to date\n"); return 0 end
        io.stderr:write(path, have and " differs from the generated rockspec — run: luajit eval/release/rockspec.lua "
            .. version .. "\n" or " is missing — run: luajit eval/release/rockspec.lua " .. version .. "\n")
        return 1
    end
    local f = assert(io.open(path, "w")); f:write(text); f:close()
    io.write("wrote ", path, " (", #M.modules(), " modules)\n")
    return 0
end

if arg and arg[0] and arg[0]:match("release/rockspec%.lua$") then os.exit(main(arg)) end
return M
